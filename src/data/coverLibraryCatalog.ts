export const GROUP_LIBRARY_COVERS = COVER_LIBRARY_CATALOG.filter((c) => c.scope === 'group');
export const FALLBACK_LIBRARY_COVERS = COVER_LIBRARY_CATALOG.filter((c) => c.scope === 'fallback');

export function findCoverLibraryEntryByUrl(url: string | undefined): CoverLibraryEntry | undefined {
  if (!url) return undefined;
  const trimmed = url.trim();
  return COVER_LIBRARY_CATALOG.find((c) => c.url === trimmed);
}

export function findCoverLibraryEntryById(id: string | undefined): CoverLibraryEntry | undefined {
  if (!id) return undefined;
  return COVER_LIBRARY_CATALOG.find((c) => c.id === id);
}
