/**
 * Enriches any active TagDesignTemplate with its curated 4-shot gallery URLs,
 * multi-category secondaryDomains, subCategory labels, Free starter flag, and popularity/recency metrics.
 * Non-destructive: preserves original design IDs, artwork URLs, print specs, and core decisions.
 */
export function applyLibraryShowcaseRegistry(template: TagDesignTemplate): TagDesignTemplate {
  const entry = LIBRARY_SHOWCASE_REGISTRY[template.id];
  if (!entry) return template;

  const galleryUrls = getShowcaseGalleryUrlsForSlug(template.slug);
  const mergedTags = Array.from(
    new Set([...(template.tags || []), ...(entry.extraTags || [])])
  );
  const isFree = Boolean(entry.isFreeStarter || template.isFree);

  return {
    ...template,
    domainCategory: entry.primaryDomain || template.domainCategory || 'personal',
    secondaryDomains: entry.secondaryDomains || template.secondaryDomains || [],
    subCategoryAr: entry.subCategoryAr,
    subCategoryEn: entry.subCategoryEn,
    requiresIpVerification:
      entry.requiresIpVerification !== undefined
        ? entry.requiresIpVerification
        : template.requiresIpVerification,
    isFree,
    priceSar: isFree ? 0 : template.priceSar,
    priceUsd: isFree ? 0 : template.priceUsd,
    includedInTier: isFree ? 'free' : template.includedInTier,
    isFeatured: entry.isFeatured !== undefined ? entry.isFeatured : template.isFeatured,
    usageCount:
      template.usageCount && template.usageCount > 0
        ? template.usageCount
        : entry.usageCount,
    salesCount:
      template.salesCount && template.salesCount > 0
        ? template.salesCount
        : isFree
        ? 0
        : entry.salesCount,
    publishedAt: entry.publishedAt,
    tags: mergedTags,
    showcaseGallery: {
      ...galleryUrls,
      productLabelAr: entry.productLabelAr,
      productLabelEn: entry.productLabelEn,
      lifestyleLabelAr: entry.lifestyleLabelAr,
      lifestyleLabelEn: entry.lifestyleLabelEn,
    },
  };
}
